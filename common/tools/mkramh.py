"""Generate a C header naming NES RAM from the Markdown tables (ram.md, notes).

    python3 mkramh.py OUT.h FILE.md...

Each RAM row `| $XX | name | meaning |` becomes `#define name nes_ram[0xXX]`;
a range `$XX-$YY` becomes `#define name (&nes_ram[0xXX])`, so it can be
indexed like the original `name,x`. Only $0000-$07FF is emitted.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from trace6502 import names_from_markdown  # noqa: E402


def main() -> None:
    out, sources = Path(sys.argv[1]), sys.argv[2:]
    ram: dict[int, tuple[str, str, int]] = {}
    for src in sources:
        r, _ = names_from_markdown(Path(src))
        for a, v in r.items():
            ram.setdefault(a, v)
    lines = ["// Generated by common/tools/mkramh.py from " + ", ".join(Path(s).name for s in sources) + ".",
             "#pragma once", "", '#include "vnes.h"', ""]
    seen: dict[str, int] = {}
    for a in sorted(ram):
        name, comment, size = ram[a]
        if a >= 0x800:
            continue
        if name in seen:
            raise SystemExit(f"mkramh: {name} names both ${seen[name]:04X} and ${a:04X}")
        seen[name] = a
        comment = comment.replace("*/", "* /")
        if size == 1:
            lines.append(f"#define {name} nes_ram[0x{a:03X}] /* {comment} */")
        else:
            lines.append(f"#define {name} (&nes_ram[0x{a:03X}]) /* {size} bytes: {comment} */")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
